import { useEffect, useState } from "react";
import { createPortal } from "react-dom";

/**
 * Место для предпросмотра — одно на весь экран, слева.
 *
 * Предпросмотров в работе несколько: момент из обзора, кадр с субтитрами,
 * рамка кадрирования, готовый ролик. Раньше каждый жил внутри своей панели,
 * и они наперебой занимали место: настраиваешь субтитры — картинка в одном
 * углу, крутишь кадрирование — в другом, а вертикальный кадр в широкой
 * колонке всё равно выходил маленьким.
 *
 * Панель по-прежнему делает свой предпросмотр сама — здесь только переносится
 * место, где он появляется. Логика остаётся при своей панели: у обзора
 * моментов это тот же самый плеер, по которому двигают границы, и разрывать
 * его с управлением нельзя.
 *
 * Вкладка в каждый момент открыта одна, поэтому и предпросмотр в полосе
 * оказывается один — без всякого разбора, кто главнее.
 */

/** Куда переносить. Полоса объявляет это место своим `id`. */
export const PREVIEW_SLOT_ID = "preview-slot";

export function PreviewSlot({
  children,
  active = true,
}: {
  children: React.ReactNode;
  /**
   * Занимать ли полосу. На вкладке роликов панелей с предпросмотром сразу
   * три — кадрирование, субтитры и сам ролик, — и полоса одна. Занимает её
   * то, с чем человек сейчас работает; решает это страница, потому что
   * только она видит их все.
   */
  active?: boolean;
}) {
  const [target, setTarget] = useState<HTMLElement | null>(null);

  // Место ищется после отрисовки: в момент первого прохода полосы ещё нет
  // в документе. Пересматривается на каждой отрисовке — полоса появляется
  // и исчезает вместе с шириной окна.
  useEffect(() => {
    setTarget(document.getElementById(PREVIEW_SLOT_ID));
  });

  // Нет полосы — на узком экране её и не должно быть. Тогда предпросмотр
  // остаётся там же, где стоит в разметке панели: показать его на месте
  // лучше, чем не показать вовсе.
  if (!active) return null;
  return target ? createPortal(children, target) : <>{children}</>;
}
