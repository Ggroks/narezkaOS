"""Сглаживание траектории кадрирования.

BAZA.md §17. Детектор выдаёт положение лица в каждом кадре, и если вести
рамку прямо по нему, ролик становится невозможно смотреть: рамка дрожит на
шуме детекции, дёргается на пропущенных кадрах и мечется при повороте головы.

Три средства, и каждое лечит свою болезнь:

- **мёртвая зона** — рамка не двигается вовсе, пока объект не ушёл заметно
  от центра. Лечит дрожание: без неё рамка отзывается на каждый пиксель шума;
- **сглаживание** (экспоненциальное среднее) — движение размазывается по
  времени, резкий скачок превращается в плавный переход;
- **предел скорости** — рамка не может двигаться быстрее заданного, что бы
  ни показал детектор. Лечит рывки на ложных срабатываниях: одиночная
  ошибка детектора на другом конце кадра не утащит рамку за собой.

**Почему не фильтр Калмана.** Он был бы уместнее, если бы мы предсказывали
движение вперёд. Но кадрирование считается по уже снятой записи, где будущее
известно, и предсказывать нечего — а настройка Калмана требует моделей шума,
которых у нас нет. Экспоненциальное среднее с пределом скорости даёт тот же
результат при вчетверо меньшем количестве настраиваемых чисел.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

#: Доля новой позиции в сглаженной. Меньше — плавнее и с большим отставанием.
#: 0.15 подобрана как компромисс: рамка догоняет заметное движение примерно
#: за полсекунды при 30 кадрах в секунду.
SMOOTHING = 0.15

#: Мёртвая зона в долях ширины **видимого кадра**, а не исходника. Пока
#: объект внутри — рамка стоит. Отсчитывать от исходника неверно: при кропе
#: 600 px из 1280 зона вышла бы в 320 px, то есть больше половины того, что
#: видит зритель, и рамка отставала бы на треть экрана.
#: Четверть: меньше даёт заметное дрожание, больше — объект успевает дойти
#: до края, прежде чем рамка тронется.
DEAD_ZONE = 0.25

#: Предел скорости в долях ширины видимого кадра за секунду. Полторы ширины в секунду
#: — быстро для взгляда, но не рывок; ложное срабатывание на другом краю
#: кадра не утащит рамку за собой мгновенно.
MAX_SPEED = 1.5


@dataclass(frozen=True)
class Track:
    """Сглаженная траектория центра рамки."""

    #: Положение центра по горизонтали в каждый момент, пиксели.
    x: np.ndarray
    #: Моменты времени, секунды.
    times: np.ndarray

    @property
    def travel(self) -> float:
        """Суммарный путь рамки. Мера того, насколько ролик подвижен."""
        return float(np.abs(np.diff(self.x)).sum()) if self.x.size > 1 else 0.0

    def at(self, moment: float) -> float:
        """Положение в произвольный момент — линейной интерполяцией.

        Детекция идёт реже, чем кадры видео (§17: 5–10 раз в секунду хватает),
        а рамку нужно ставить в каждом кадре.
        """
        if self.x.size == 0:
            return 0.0
        return float(np.interp(moment, self.times, self.x))


def smooth(
    positions: list[float | None],
    times: list[float],
    crop_width: float,
    *,
    smoothing: float = SMOOTHING,
    dead_zone: float = DEAD_ZONE,
    max_speed: float = MAX_SPEED,
) -> Track:
    """Сглаживает последовательность положений объекта.

    `crop_width` — ширина видимого кадра, а не исходника: заметность движения
    определяется тем, что видит зритель. От неё же считаются мёртвая зона
    и предел скорости.

    `None` означает, что в этот момент детектор ничего не нашёл. Такие
    моменты не считаются нулём и не обрываются: рамка просто продолжает
    стоять там, где стояла. Пропуск детекции — обычное дело, и дёргать
    рамку в начало кадра из-за него нельзя.
    """
    if not positions or len(positions) != len(times):
        return Track(np.zeros(0), np.zeros(0))

    dead = dead_zone * crop_width
    speed_limit = max_speed * crop_width

    # Начальное положение — первая находка, а не центр кадра: иначе ролик
    # начинается с проезда от середины к объекту.
    first = next((p for p in positions if p is not None), crop_width / 2)
    current = float(first)

    result = np.empty(len(positions), dtype=np.float64)
    for index, (target, moment) in enumerate(zip(positions, times, strict=True)):
        if target is not None:
            offset = target - current
            if abs(offset) > dead:
                # Тянемся не к самой цели, а к краю мёртвой зоны: иначе
                # рамка при каждом выходе за зону подтягивала бы объект
                # обратно в центр, и получалось бы покачивание.
                goal = target - np.sign(offset) * dead
                step = (goal - current) * smoothing

                if index > 0:
                    elapsed = max(moment - times[index - 1], 1e-6)
                    limit = speed_limit * elapsed
                    step = float(np.clip(step, -limit, limit))
                current += step
        result[index] = current

    return Track(result, np.asarray(times, dtype=np.float64))


def crop_centre(track: Track, moment: float, crop_width: float, frame_width: float) -> float:
    """Левая граница кропа для момента, прижатая к краям кадра.

    Прижатие обязательно: рамка, уехавшая за край, дала бы чёрную полосу,
    а ffmpeg на отрицательном смещении просто откажется работать.
    """
    left = track.at(moment) - crop_width / 2
    return float(np.clip(left, 0.0, max(0.0, frame_width - crop_width)))


#: Насколько положение должно измениться, чтобы стать опорной точкой кривой.
#: Кривая передаётся ffmpeg выражением, и каждая точка — это лишние символы:
#: минутный ролик при пяти находках в секунду дал бы триста звеньев. Порог
#: в несколько пикселей отбрасывает те, что зритель всё равно не различит.
KEYFRAME_THRESHOLD = 4.0


def keyframes(track: Track, threshold: float = KEYFRAME_THRESHOLD) -> list[tuple[float, float]]:
    """Опорные точки траектории: только там, где положение заметно менялось.

    Первая и последняя оставляются всегда — без них выражение не покрывает
    края ролика, и ffmpeg на этих участках получил бы неопределённость.
    """
    if track.x.size == 0:
        return []
    if track.x.size == 1:
        return [(float(track.times[0]), float(track.x[0]))]

    points = [(float(track.times[0]), float(track.x[0]))]
    for moment, value in zip(track.times[1:-1], track.x[1:-1], strict=True):
        if abs(value - points[-1][1]) >= threshold:
            points.append((float(moment), float(value)))
    points.append((float(track.times[-1]), float(track.x[-1])))
    return points


def crop_expression(
    points: list[tuple[float, float]], crop_width: float, frame_width: float
) -> str:
    """Выражение для параметра `x` фильтра crop — кусочно-линейная кривая.

    ffmpeg вычисляет его на каждом кадре, подставляя время в `t`. Кусками,
    а не одной формулой, потому что траектория произвольная: между опорными
    точками положение меняется линейно, а на границах ролика удерживается.

    Прижатие к краям делается **здесь**, а не в самом выражении: `min` и `max`
    внутри каждого звена утроили бы его длину, а результат тот же — точки
    уже прижаты, и линия между двумя прижатыми точками не выходит за края.
    """
    if not points:
        return "0"

    limit = max(0.0, frame_width - crop_width)

    def left(value: float) -> float:
        return min(max(value - crop_width / 2, 0.0), limit)

    if len(points) == 1:
        return f"{left(points[0][1]):.1f}"

    # Плоская сумма, а не вложенные условия. Вложенность у ffmpeg ограничена,
    # и на 190 звеньях разбор выражения падает с «too many args» — проверено.
    # Здесь каждое звено умножается на признак своего промежутка и попадает
    # в сумму, поэтому глубина всегда единица, какой бы длинной ни была
    # траектория.
    #
    # Промежутки полуоткрытые: `between` включает оба конца, и на стыках
    # два соседних звена сложились бы, дав скачок вдвое.
    terms: list[str] = []
    first_t = points[0][0]
    terms.append(f"lt(t,{first_t:.3f})*{left(points[0][1]):.1f}")

    for (t0, x0), (t1, x1) in zip(points, points[1:], strict=False):
        a, b = left(x0), left(x1)
        span = max(t1 - t0, 1e-6)
        slope = (b - a) / span
        terms.append(
            f"gte(t,{t0:.3f})*lt(t,{t1:.3f})*({a:.1f}+{slope:.4f}*(t-{t0:.3f}))"
        )

    last_t, last_x = points[-1]
    terms.append(f"gte(t,{last_t:.3f})*{left(last_x):.1f}")
    return "+".join(terms)
